"""gen_tables.py: write unicode_tables.h from the Python that is the reference (3.11.9, the corpus header names it), so the device reads
digits and whitespace exactly as Python's str.strip(), re's \\d and \\s, and int() do.

- every Unicode decimal digit (category Nd) comes in a run of ten from a zero; the table lists each zero's code point;
- the whitespace set is every code point c with chr(c).isspace() (str.strip() and re's \\s for str patterns use this set).
python cuda/mathbackend/gen_tables.py   (rewrites cuda/mathbackend/unicode_tables.h)
"""
import sys
import unicodedata
from pathlib import Path

zeros = []
for c in range(sys.maxunicode + 1):
    ch = chr(c)
    if unicodedata.category(ch) == 'Nd' and unicodedata.decimal(ch, None) == 0:
        assert all(unicodedata.decimal(chr(c + k), None) == k for k in range(10)), hex(c)
        zeros.append(c)
spaces = [c for c in range(sys.maxunicode + 1) if chr(c).isspace()]
# re's \d for str patterns is exactly category Nd; check the runs cover it
nd = [c for c in range(sys.maxunicode + 1) if unicodedata.category(chr(c)) == 'Nd']
assert sorted(z + k for z in zeros for k in range(10)) == nd

out = Path(__file__).with_name('unicode_tables.h')
out.write_text(
    '// generated by gen_tables.py from Python ' + sys.version.split()[0] + ', unicodedata ' + unicodedata.unidata_version + '; do not edit\n'
    '#pragma once\n#include <stdint.h>\n'
    f'#define MIP_ND_ZEROS {len(zeros)}\n'
    '__device__ __constant__ uint32_t mip_nd_zero[MIP_ND_ZEROS] = {' + ', '.join(f'0x{z:X}' for z in zeros) + '};\n'
    f'#define MIP_SPACES {len(spaces)}\n'
    '__device__ __constant__ uint32_t mip_space[MIP_SPACES] = {' + ', '.join(f'0x{s:X}' for s in spaces) + '};\n',
    encoding='utf-8', newline='\n')
print(f'{out}: {len(zeros)} digit runs, {len(spaces)} whitespace code points')
